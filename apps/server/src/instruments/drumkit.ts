/**
 * Normalised drum kits. Big kits ship complex SFZ programs (CC-driven mic blends, #includes, curves). Instead of
 * implementing all of that, the fetch step picks the samples Riff Roll needs and writes a simple SFZ in Riff Roll's
 * drum keymap (see packages/core/src/drums.ts): close + overhead mics layered, every velocity layer, two round robins,
 * choke groups for hi-hat and cymbals.
 */

export interface KitPieceMap {
  key: number;
  /** directory prefix inside the archive, e.g. "Samples/kick_24/kick/" (mic folders below it) */
  dir: string;
  /** mic folder -> volume in dB */
  mics: Record<string, number>;
  group?: number;
  offBy?: number;
  tune?: number; // cents
  volume?: number; // dB for the whole piece
}

