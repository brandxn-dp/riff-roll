const MIC_NAME: Record<string, string> = { kick: 'close', top: 'close', btm: 'close', cl: 'close', oh: 'oh' };

interface Parsed {
  path: string;
  mic: string;
  vl: number;
  rr: number;
}

function parse(path: string, dir: string): Parsed | null {
  if (!path.startsWith(dir) || !/\.(flac|wav)$/i.test(path)) return null;
  const rest = path.slice(dir.length).split('/');
  if (rest.length !== 2) return null;
  const m = /_vl(\d+)_rr(\d+)\.\w+$/i.exec(rest[1]) ?? /_rr(\d+)\.\w+$/i.exec(rest[1]);
  if (!m) return null;
  return m.length === 3
    ? { path, mic: rest[0], vl: Number(m[1]), rr: Number(m[2]) }
    : { path, mic: rest[0], vl: 1, rr: Number(m[1]) };
}

/** Which archive entries the kit needs (all velocity layers, `roundRobins` RRs, chosen mics). */
export function selectKitFiles(entries: string[], map: KitPieceMap[], roundRobins = 2): string[] {
  const out = new Set<string>();
  for (const piece of map)
    for (const e of entries) {
      const p = parse(e, piece.dir);
      if (p && p.rr <= roundRobins && piece.mics[p.mic] !== undefined) out.add(e);
    }
  return [...out];
}

/** Write the normalised SFZ for the selected files. */
export function kitSfz(files: string[], map: KitPieceMap[], roundRobins = 2): string {
  const lines = [
    '// Generated by Riff Roll fetch-instruments: Riff Roll drum keymap, close + overhead mics.',
    '<control>',
    '<global> loop_mode=one_shot ampeg_release=0.05 off_mode=fast',
  ];
  for (const piece of map) {
    const parsed = files.map((f) => parse(f, piece.dir)).filter((p): p is Parsed => !!p && piece.mics[p.mic] !== undefined);
    if (!parsed.length) continue;
    const layers = Math.max(...parsed.map((p) => p.vl));
    const rrs = Math.min(roundRobins, Math.max(...parsed.map((p) => p.rr)));
    lines.push(`<group> key=${piece.key} pitch_keytrack=0${piece.group ? ` group=${piece.group}` : ''}${piece.offBy ? ` off_by=${piece.offBy}` : ''}${piece.tune ? ` tune=${piece.tune}` : ''} seq_length=${rrs} amp_veltrack=40`);
    for (const p of parsed.sort((a, b) => a.mic.localeCompare(b.mic) || a.vl - b.vl || a.rr - b.rr)) {
      if (p.rr > rrs) continue;
      const lo = Math.floor(((p.vl - 1) * 127) / layers) + 1;
      const hi = Math.floor((p.vl * 127) / layers);
      const vol = (piece.mics[p.mic] ?? 0) + (piece.volume ?? 0);
      lines.push(
        `<region> lovel=${lo} hivel=${hi} seq_position=${p.rr} volume=${vol} riffroll_mic=${MIC_NAME[p.mic] ?? p.mic} sample=${p.path}`,
      );
    }
  }
  return lines.join('\n') + '\n';
}
